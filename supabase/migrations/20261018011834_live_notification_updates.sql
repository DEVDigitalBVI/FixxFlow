-- Postgres Changes applies the existing recipient, membership and MFA RLS policies.
-- Preserve projects where notifications were already enabled through the dashboard.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end;
$$;
